#!/usr/bin/env bash
#
# slim-history.sh — rewrite git history to purge dead/duplicate large blobs.
#
# DO NOT RUN THIS UNTIL YOU HAVE READ THIS WHOLE COMMENT BLOCK.
#
# WHAT THIS DOES
#   Runs `git filter-repo` to strip a fixed list of paths from EVERY commit
#   in the repo's history, then expires the reflog and gcs the object store.
#   Only paths that are already gone from the current HEAD tree, or that
#   this cleanup's own commits removed from HEAD, are targeted — nothing
#   currently checked out is deleted from the working tree.
#
# SIZE (measured 2026-08-03, on branch chore/slim-repo before any rewrite):
#   .git today:                      ~184 MB
#   Raw blob bytes made unreachable: ~53.6 MB  (106 blobs, across the paths below)
#   Projected .git after rewrite+gc: very roughly ~125–135 MB
#     (estimate only — most of these blobs are already-compressed video/gif
#     data, so further pack compression gains are small; measure the real
#     number with `du -sh .git` after running this for real)
#
#   NOT reclaimed by this rewrite (verified still referenced by a path that
#   survives at HEAD, so filter-repo correctly leaves the blob in the pack):
#     - foil-rl-pump/python-rl/videos/sustained_60s.mp4 (23.75 MB) — shares
#       its blob with the old reinforcement-learning/sustained_60s.mp4 path
#     - foil-board-optimizer/comparison.html, viewer.html, force_viewer.html
#       — share blobs with their old site/apps/board/* mirrors
#     - foil-rl-pump/python-rl/checkpoints/baseline_2M/model_100pct.zip
#       (1.79 MB) — shares its blob with the old
#       reinforcement-learning/checkpoints/ent005_2M/model_100pct.zip path
#   These files are still tracked at HEAD (see the project's CLAUDE.md /
#   README for why: they are not verified-regenerable, or are the live
#   source-of-truth copy) — this script cannot shrink them further without
#   deleting them from HEAD, which is a separate decision.
#
# THIS REWRITES EVERY COMMIT SHA IN THE REPOSITORY.
#   - Every existing local clone (including this one, after the rewrite) and
#     every fork will have a completely different commit history graph from
#     what's on GitHub today.
#   - It requires a force push (`git push --force` to main) to publish.
#   - After it's pushed, everyone with an existing clone — including you on
#     any other machine — MUST re-clone. `git pull` will not cleanly
#     reconcile a filter-repo rewrite; it will produce a confusing merge of
#     old and new histories at best, and silent duplication at worst.
#   - Any open PRs, branches, or local commits not yet on the rewritten
#     main will need to be manually re-applied (cherry-pick onto the new
#     history) before or after the rewrite — they will not carry over.
#   - GitHub PR/issue links that reference specific commit SHAs will still
#     resolve (GitHub keeps orphaned commits reachable for a while), but
#     `git blame`/`git log` on the new history will not show the old SHAs.
#
# PATHS BEING PURGED FROM ALL HISTORY (see comment above each group):
#   site/apps/                                    — dupes of live source files,
#                                                    regenerated by site/refresh-embeds.sh
#   foil-mocap/pose_landmarker_full.task           — downloadable MediaPipe model
#   foil-mocap/samples/output/slowmo_pump_dots_trace.mp4  — regenerable, see foil-mocap/regen.sh
#   reinforcement-learning/                        — superseded by foil-rl-pump/, already gone from HEAD
#   archive/                                       — pre-reorg legacy dir, already gone from HEAD
#   foil_env/                                      — pre-reorg legacy dir, already gone from HEAD
#   mujoco/                                        — pre-reorg legacy dir (top-level only —
#                                                    NOT foil-rl-pump/mujoco/, which stays)
#   docs/                                          — pre-reorg legacy dir (top-level only —
#                                                    NOT foil-rl-pump/mujoco/docs/, which stays)
#   requirements.txt                               — pre-reorg top-level leftover (exact path only —
#                                                    NOT any project's own requirements.txt)
#   MIGRATION.md, CLAUDE.md                        — pre-reorg top-level leftovers (exact path only —
#                                                    NOT any project's own CLAUDE.md)
#
# NOT purged, deliberately (still live at HEAD, kept — see repo-cleanup report):
#   foil-board-optimizer/media/*.mp4, comparison.html, viewer.html, force_viewer.html
#   foil-mocap/samples/output/slowmo_pump_combined.mp4
#   foil-rl-pump/python-rl/videos/*.mp4
#   foil-rl-pump/python-rl/checkpoints/baseline_2M/model_100pct.zip
#
# PREREQUISITES
#   - git-filter-repo installed (`brew install git-filter-repo` or `pip install git-filter-repo`)
#   - Run this on a FRESH, throwaway clone/mirror — not your only working
#     copy, and not a repo with uncommitted work. filter-repo refuses to run
#     on a repo with an existing remote unless given --force, precisely to
#     stop you from doing this by accident on your primary checkout:
#       git clone --no-local /path/to/foil-experiments foil-experiments-rewrite
#       cd foil-experiments-rewrite
#       bash /path/to/scripts/slim-history.sh
#   - Coordinate the force-push and mandatory re-clone with anyone else
#     using this repo BEFORE you push.
#
# This script will refuse to do anything until you set I_UNDERSTAND=1 and
# pass --yes-really-rewrite-history on the command line.

set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

if [[ "${1:-}" != "--yes-really-rewrite-history" || "${I_UNDERSTAND:-0}" != "1" ]]; then
  cat <<'EOF'
Refusing to run.

This rewrites every commit SHA in the repository and requires a force
push plus a mandatory re-clone by every other user of this repo. Read
the full comment block at the top of this script first.

If you have read it and definitely want to proceed:

  I_UNDERSTAND=1 bash scripts/slim-history.sh --yes-really-rewrite-history

EOF
  exit 1
fi

if ! command -v git-filter-repo >/dev/null 2>&1; then
  echo "git-filter-repo is not installed. Install it first:" >&2
  echo "  brew install git-filter-repo" >&2
  exit 1
fi

echo "This repo currently has a remote configured:"
git remote -v
echo
echo "Strongly recommended: run this on a disposable clone, not this checkout."
read -r -p "Type the repo's current branch name (shown by 'git branch --show-current') to confirm you know what you're rewriting: " confirm_branch
current_branch="$(git branch --show-current)"
if [[ "$confirm_branch" != "$current_branch" ]]; then
  echo "Branch name didn't match ('$confirm_branch' != '$current_branch'). Aborting." >&2
  exit 1
fi

echo
echo "Before size:"
du -sh .git

git filter-repo --force \
  --path site/apps \
  --path foil-mocap/pose_landmarker_full.task \
  --path foil-mocap/samples/output/slowmo_pump_dots_trace.mp4 \
  --path reinforcement-learning \
  --path archive \
  --path foil_env \
  --path mujoco \
  --path docs \
  --path requirements.txt \
  --path MIGRATION.md \
  --path CLAUDE.md \
  --invert-paths

git reflog expire --expire=now --all
git gc --prune=now --aggressive

echo
echo "After size:"
du -sh .git

cat <<'EOF'

Done rewriting local history. Nothing has been pushed yet.

Next steps (do these deliberately, not automatically):
  1. Inspect the result: git log --oneline | head; git status
  2. Re-add the 'origin' remote if filter-repo removed it (it does, by design):
       git remote add origin <url>
  3. Force-push, and only after you've told every other user of this repo
     to re-clone once it's up:
       git push --force origin <branch>
  4. Every other clone of this repo (including any other machine of yours)
     must be re-cloned from scratch — do not 'git pull' into them.
EOF
